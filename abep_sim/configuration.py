"""Authoritative input manifests (A9.22 layer separation; A9.23 simulation architecture): loaders for ``config/`` and
the ``SimulationConfiguration`` record.

Owner directives 2026-10-03 (docs/decisions/OD_2026_10_03_A9_22_*, OD_2026_10_03_A9_23_*): requirements / provenance
-> frozen engineering constraints; architecture + constraints + design states + physics -> raw results; raw results +
constraints -> assessment. The physics never reads or interprets the RFP / RVM / clause ids; it consumes versioned,
sha256-pinned configuration files. This module is that interface:

  config/MANIFEST.json                                  every config file + sha256 (root of trust for this directory)
  config/SOURCES_OF_TRUTH.json                          one authoritative artefact per role (A9.23)
  config/architecture/hall_icp_neutralizer_v1.json      A9.19 / A9.20 / A9.15 flight architecture (design layer)
  config/constraints/engineering_constraints_v1.json    frozen engineering constraints (values; provenance labels only)
  config/requirements/rfp_constraints_v1.json           requirements snapshot (PROVENANCE layer; read only by the
                                                        assessment loaders below, never by physics / design seams)
  config/mission/mission_scenario_v2.json               frozen operating scenario (A9.24 item 4): independently versioned
                                                        operating-scenario choices + value-free references to constraints;
                                                        pinned here by id + version + sha256 (OPERATING_SCENARIO_PIN)
  config/mission/mission_scenario_v1.json               HISTORICAL (superseded by v2, kept byte-identical, never loaded)
  config/assessment/gate_thresholds_v1.json             assessment-layer HC-05..HC-12 gate thresholds (A9.24 item 5)
  config/environment/design_state_set_ref_v1.json       REFERENCE to the frozen design-state set v2 (never a copy)
  config/hardware/hardware_bounds_v1.json               INDEX of hardware-limit sources (path + sha256 + locator)
  config/model_set/physics_model_set_v1.json            physics module / data hashes and version labels

Every loader fails closed: a file missing from the manifest, a file whose sha256 differs from the manifest, or a
referenced file whose sha256 differs from the pin raises ``ConfigurationError`` (no fallback, CLAUDE.md rule 3).
The files are generated by ``scripts/config/build_config.py`` from the existing sources. ``abep_sim.constants.RFP``
keeps its recorded values (immutable; its mission_hours = 26,000 h is HISTORICAL_CONSTANT_NOT_CONSUMED since the
A9.22 G1 governed migration). The seams ``abep_sim.operating_inputs`` (physics) and
``abep_sim.design.engineering_constraints`` (design) read their values through ``load_operating_inputs`` and
``load_engineering_constraints`` below; both read config/constraints (+ config/mission), never config/requirements.

``physics_configuration()`` is the raw-physics entry point: it never opens the requirements snapshot.
The config root is ``<repository>/config``; ``ABEP_CONFIG_ROOT`` overrides it (used when the package is installed
outside a checkout). There is no packaged fallback copy.
"""
