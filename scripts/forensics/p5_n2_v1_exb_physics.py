def official_status(scores):
    st = collections.defaultdict(dict)
    for r in scores["runs"]:
        st[r["key"]][r["reading"]] = r["status"]
    return st


def run_row(r, audit, cases, ens, status):
    """Descriptive per-run quantities (N1-N3). Pure function of the frozen record."""
    ions = r["outlet_ions"]
    total = sum(v["flux_m2s"] for v in ions.values())
    n2p, np_, nz2 = ions["N2_Z1"], ions["N_Z1"], ions.get("N_Z2")
    obs = audit[r["point"]]["fig10"]
    Va = {"N2+": va("N2", n2p["u_ms"], n2p["Z"]), "N+": va("N", np_["u_ms"], np_["Z"])}
    Va_nu = {"N2+": va("N2", n2p["flux_m2s"] / n2p["n_m3"], 1), "N+": va("N", np_["flux_m2s"] / np_["n_m3"], 1)}
    row = {
        "key": r["key"], "candidate": r["candidate"], "chemistry": r["chemistry"], "point": r["point"],
        "registration": r["registration"], "coil_shape": r["coil_shape"],
        "status_A": status[r["key"]]["A"], "status_B": status[r["key"]]["B"],
        "domain_class": "OUT_OF_DOMAIN" if status[r["key"]]["A"] == "OUT_OF_DOMAIN" else "SCOREABLE",
        "Te_max_eV": r["Te_max_eV"], "Id_rms_rel": r["Id_rms_rel"], "V_d": audit[r["point"]]["table2"]["V_d"],
        "transport": ens[r["candidate"]],
        "outlet_z_minus_exit_m": cases[r["case"]]["domain_m"] - cases[r["case"]]["L_m"],
        "Va_N2p": Va["N2+"], "Va_Np": Va["N+"],
        "Va_N2p_nu_over_n": Va_nu["N2+"], "Va_Np_nu_over_n": Va_nu["N+"],
        "Va_NZ2_per_charge": va("N", nz2["u_ms"], nz2["Z"]) if nz2 else None,
        "Va_NZ2_per_charge_nu_over_n": va("N", nz2["flux_m2s"] / nz2["n_m3"], nz2["Z"]) if nz2 else None,
        "u_N2p": n2p["u_ms"], "u_Np": np_["u_ms"], "u_NZ2": nz2["u_ms"] if nz2 else None,
        "ff_N2p": n2p["flux_m2s"] / total, "ff_Np": np_["flux_m2s"] / total,
        "ff_NZ2": nz2["flux_m2s"] / total if nz2 else 0.0,
        "N2_Z2_present": "N2_Z2" in ions,
        "species_keys": sorted(ions),
        "obs_Va_N2p": obs["Va_N2plus_V"], "obs_Va_Np": obs["Va_Nplus_V"],
    }
    row["D"] = row["Va_Np"] - row["Va_N2p"]
    row["D_nu_over_n"] = row["Va_Np_nu_over_n"] - row["Va_N2p_nu_over_n"]
    row["R"] = row["Va_Np"] / row["Va_N2p"]
    row["u_ratio_Np_N2p"] = row["u_Np"] / row["u_N2p"]
    row["dVa_Np"] = row["Va_Np"] - row["obs_Va_Np"]
    row["dVa_N2p"] = row["Va_N2p"] - row["obs_Va_N2p"]
    row["ordering"] = row["Va_Np"] > row["Va_N2p"]
    row["ordering_nu_over_n"] = row["Va_Np_nu_over_n"] > row["Va_N2p_nu_over_n"]
    # Energy each species would be assigned under the E x B "m/Z = 14 amu/e" label (a Wien filter selects velocity only):
    # E_14 = m_N u^2 / (2 e). N+: = V_a(N+); N2+ (m/Z 28): = V_a(N2+) * (m_N / m_N2); N^2+ (m/Z 7): = 2 x per-charge energy.
    row["E14_N2p"] = MASS["N"] * row["u_N2p"] ** 2 / (2 * E)
    row["E14_Np"] = MASS["N"] * row["u_Np"] ** 2 / (2 * E)
    row["E14_NZ2"] = MASS["N"] * row["u_NZ2"] ** 2 / (2 * E) if nz2 else None
    return row


def reproduce(rows, scores):
    exb = scores["exb_diagnostic"]
    dev = {"N2+": 0.0, "N+": 0.0}
    flag_mismatch, missing = 0, []
    for row in rows:
        o = exb.get(row["key"])
        if o is None:
            missing.append(row["key"]); continue
        dev["N2+"] = max(dev["N2+"], abs(row["Va_N2p"] - o["N2+"]["Va_model_V"]))
        dev["N+"] = max(dev["N+"], abs(row["Va_Np"] - o["N+"]["Va_model_V"]))
        flag_mismatch += int(row["ordering"] != o["ordering_Nplus_above_N2plus"])
    official_true = sum(1 for v in exb.values() if v.get("ordering_Nplus_above_N2plus"))
    return {"n_runs_recomputed": len(rows), "n_official_exb_entries": len(exb),
            "keys_identical": sorted(r["key"] for r in rows) == sorted(exb),
            "missing_in_official": missing,
            "max_abs_dev_Va_V": {k: v for k, v in dev.items()}, "ordering_flag_mismatches": flag_mismatch,
            "ordering_true_recomputed": sum(r["ordering"] for r in rows), "ordering_true_official": official_true}


def reading_consistency(rows):
    """Official statuses under readings A and B (read, never recomputed). domain_class uses reading A; this checks that
    OUT_OF_DOMAIN is identical under both readings and lists the keys whose A/B statuses differ (PASS vs FAIL_VALIDATION)."""
    ood_diff = [r["key"] for r in rows if (r["status_A"] == "OUT_OF_DOMAIN") != (r["status_B"] == "OUT_OF_DOMAIN")]
    mixed = sorted((r["key"], r["status_A"], r["status_B"]) for r in rows if r["status_A"] != r["status_B"])
    scoreable = [r for r in rows if r["domain_class"] != "OUT_OF_DOMAIN"]
    return {"n_keys_ood_differs_between_readings": len(ood_diff),
            "n_not_ood_keys": len(scoreable),
            "n_mixed_reading_keys": len(mixed),
            "mixed_reading_keys": [{"key": k, "status_A": a, "status_B": b} for k, a, b in mixed],
            "ordering_count_in_mixed_reading_keys": sum(r["ordering"] for r in rows if r["status_A"] != r["status_B"]),
            "note": "OUT_OF_DOMAIN is decided per key (chemistry validity) and is the same under readings A and B; the "
                    "mixed-reading keys differ only between PASS and FAIL_VALIDATION."}


def group_summary(rows):
    return {
        "n": len(rows), "n_out_of_domain": sum(r["domain_class"] == "OUT_OF_DOMAIN" for r in rows),
        "Va_N2p": stats([r["Va_N2p"] for r in rows]), "Va_Np": stats([r["Va_Np"] for r in rows]),
        "Va_NZ2_per_charge": stats([r["Va_NZ2_per_charge"] for r in rows]),
        "D": stats([r["D"] for r in rows]), "R": stats([r["R"] for r in rows], ROUND_F),
        "u_ratio_Np_N2p": stats([r["u_ratio_Np_N2p"] for r in rows], ROUND_F),
        "ff_N2p": stats([r["ff_N2p"] for r in rows], ROUND_F), "ff_Np": stats([r["ff_Np"] for r in rows], ROUND_F),
        "ff_NZ2": stats([r["ff_NZ2"] for r in rows], ROUND_F),
        "dVa_Np": stats([r["dVa_Np"] for r in rows]), "dVa_N2p": stats([r["dVa_N2p"] for r in rows]),
        "Te_max_eV": stats([r["Te_max_eV"] for r in rows]),
        "Va_N2p_over_Vd": stats([r["Va_N2p"] / r["V_d"] for r in rows], ROUND_F),
        "Va_Np_over_Vd": stats([r["Va_Np"] / r["V_d"] for r in rows], ROUND_F),
        "ordering_count": sum(r["ordering"] for r in rows),
        "ordering_count_nu_over_n": sum(r["ordering_nu_over_n"] for r in rows),
    }


def grouped(rows, keyf):
    g = collections.defaultdict(list)
    for r in rows:
        g[keyf(r)].append(r)
    return {k: group_summary(g[k]) for k in sorted(g)}


def te_bin(te):
    for lo, hi in ((0, 15), (15, 18), (18, 21), (21, 1e9)):
        if lo <= te < hi:
            return f"{lo}-{hi}" if hi < 1e9 else f">={lo}"


def rms_band(x):
    return "<1" if x < 1 else ("1-3" if x < 3 else ">=3")


def measured_block(audit):
    out = {}
    for p in POINTS:
        f = audit[p]["fig10"]
        a, b = f["Va_N2plus_V"], f["Va_Nplus_V"]
        out[p] = {"V_d": audit[p]["table2"]["V_d"], "Va_N2p": rnd(a, ROUND_V), "Va_Np": rnd(b, ROUND_V),
                  "D": rnd(b - a, ROUND_V), "R": rnd(b / a, ROUND_F),
                  "Va_N2p_over_Vd": rnd(a / audit[p]["table2"]["V_d"], ROUND_F),
                  "Va_Np_over_Vd": rnd(b / audit[p]["table2"]["V_d"], ROUND_F),
                  "u_ratio_Np_N2p_if_labels_hold": rnd(math.sqrt((b / MASS["N"]) / (a / MASS["N2"])), ROUND_F),
                  "sigma_each_V": EXB_SIGMA_V,
                  "sigma_D_V_assuming_independent_errors": rnd(math.sqrt(2) * EXB_SIGMA_V, ROUND_V),
                  "p_chamber_Torr": audit[p]["table2"]["p_chamber_Torr_N2"]}
    return out


def vd_slopes(rows, audit):
    series = collections.defaultdict(dict)
    for r in rows:
        series[(r["candidate"], r["chemistry"], r["registration"], r["coil_shape"])][r["point"]] = r
    s2, s1, sD = [], [], []
    for k in sorted(series):
        pts = series[k]
        if set(pts) != set(POINTS):
            continue
        vd = [pts[p]["V_d"] for p in POINTS]
        s2.append(ls_slope(vd, [pts[p]["Va_N2p"] for p in POINTS]))
        s1.append(ls_slope(vd, [pts[p]["Va_Np"] for p in POINTS]))
        sD.append(ls_slope(vd, [pts[p]["D"] for p in POINTS]))
    vd = [audit[p]["table2"]["V_d"] for p in POINTS]
    m2 = ls_slope(vd, [audit[p]["fig10"]["Va_N2plus_V"] for p in POINTS])
    m1 = ls_slope(vd, [audit[p]["fig10"]["Va_Nplus_V"] for p in POINTS])
    return {"n_series": len(s2), "model_dVa_dVd_N2p": stats(s2, ROUND_F), "model_dVa_dVd_Np": stats(s1, ROUND_F),
            "model_dD_dVd": stats(sD, ROUND_F), "measured_dVa_dVd_N2p": rnd(m2, ROUND_F),
            "measured_dVa_dVd_Np": rnd(m1, ROUND_F), "measured_dD_dVd": rnd(m1 - m2, ROUND_F)}


def associations(rows):
    pairs = [("D", "Te_max_eV"), ("D", "ff_Np"), ("D", "ff_NZ2"), ("D", "Id_rms_rel"), ("Va_Np", "ff_Np"),
             ("Va_N2p", "ff_Np"), ("Va_Np", "Te_max_eV"), ("Va_N2p", "Te_max_eV"), ("R", "ff_NZ2"),
             ("D", "barrier_scale"), ("D", "center_L"), ("D", "width_L")]

    def val(r, k):
        return r["transport"][k] if k in r["transport"] else r[k]
    out = {}
    for scope in ("all",) + POINTS:
        sub = rows if scope == "all" else [r for r in rows if r["point"] == scope]
        out[scope] = {f"{a}~{b}": rnd(spearman([val(r, a) for r in sub], [val(r, b) for r in sub]), 3) for a, b in pairs}
    return out


def histogram(xs, width=10.0):
    lo = math.floor(min(xs) / width) * width
    hi = math.ceil(max(xs) / width) * width
    edges, counts = [], []
    e = lo
    while e < hi:
        edges.append([e, e + width]); counts.append(sum(1 for x in xs if e <= x < e + width)); e += width
    return {"bin_width_V": width, "bins": [{"lo": a, "hi": b, "count": c} for (a, b), c in zip(edges, counts)]}


