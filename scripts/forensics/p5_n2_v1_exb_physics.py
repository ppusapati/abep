def runs_table(rows):
    """Column-oriented per-run table (compact). Voltages and velocities rounded to 1e-4; ratios and fractions to 1e-6."""
    def cell(k, v):
        if isinstance(v, float):
            return rnd(v, ROUND_F if k.startswith(("ff_", "R", "Id_rms")) else ROUND_V)
        return v
    return {"columns": list(RUN_COLUMNS), "rows": [[cell(k, r[k]) for k in RUN_COLUMNS] for r in rows]}


