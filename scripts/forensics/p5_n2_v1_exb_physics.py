"""P5-N2 v1 vacuum campaign: E x B / species-acceleration physics forensics (NON-GATING, descriptive only).

This script never scores, re-scores or re-labels a run. Official per-run statuses and the official O5 E x B diagnostic are
READ from hallthruster_bridge/validation/p5_n2_campaign_v1_vacuum_scores.json. The v1 outcome (all nine screening
candidates INCONCLUSIVE / NOT ELIGIBLE, credible set empty) is final and is not touched. Nothing here is tuned, and no
criterion, tolerance or rate-table limit is proposed or changed. The E x B diagnostic never eliminates or admits anything.

What it does (all from frozen repository files; deterministic; no Julia, a few seconds of CPU):
  1. Recomputes, for every N1-N3 run of the frozen raw dataset, V_a,s = m_s u_s^2 / (2 Z_s e) at the model outlet from
     `outlet_ions` with the same constants and operation order as the frozen scorer (scripts/score_p5_n2_campaign.py,
     exb()), and checks it against the official `exb_diagnostic` block (value and ordering flag).
  2. Adds descriptive quantities the official block does not carry: N^2+ energy per charge, N2^2+ presence, all-species
     outlet flux fractions, D = V_a(N+) - V_a(N2+), R = V_a(N+)/V_a(N2+), velocity ratios, the alternative
     time-average definition u_eff = <n u>/<n> (both <n> and <n u> are recorded), the energy each model species would show
     under the E x B "m/Z = 14" label, discharge-voltage slopes, and rank associations with Te_max_eV, flux fractions,
     I_d oscillation and the candidate transport parameters.
  3. Groups everything by point, candidate, registration, chemistry, coil shape, official domain class and Te_max bin.

Measured side (frozen measurement audit, identification/brabston_p5_n2_measurement_audit_v1.json): Brabston et al.,
JPP 2025, doi:10.2514/1.B39623, Fig. 10 (digitized eta_V,n; V_a,n = eta_V,n V_d), E x B probe 1 m downstream of the exit
plane on centreline, bi-Gaussian peaks, Eq. (11) plasma-potential correction, Table 5 sigma 11.6 V. The propagated
sigma of a difference of two such values assumes independence (an ASSUMPTION, labelled as such in the output).

Outputs: docs/forensics/p5_n2_v1/exb_physics/exb_physics.json and exb_physics_tables.md (both regenerated byte-identically).
Usage: python scripts/forensics/p5_n2_v1_exb_physics.py [--check]   (--check: verify the committed outputs are current)
"""
