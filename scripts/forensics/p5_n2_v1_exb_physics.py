def serialize(out):
    """Deterministic: sorted keys; the per-run table is written one run per line."""
    runs = out["runs"]
    head = dict(out)
    head["runs"] = "__RUNS__"
    txt = json.dumps(head, indent=1, sort_keys=True, ensure_ascii=False)
    body = ('{\n  "columns": ' + json.dumps(runs["columns"]) + ',\n  "rows": [\n'
            + ",\n".join("   " + json.dumps(r, ensure_ascii=False) for r in runs["rows"]) + "\n  ]\n }")
    return txt.replace('"__RUNS__"', body) + "\n"


def main(argv):
    out, _ = build()
    js, md = serialize(out), tables_md(out)
    if "--check" in argv:
        ok = open(OUT_JSON).read() == js and open(OUT_MD).read() == md
        print("exb_physics outputs current:", ok)
        return 0 if ok else 1
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(OUT_JSON, "w") as f:
        f.write(js)
    with open(OUT_MD, "w") as f:
        f.write(md)
    rep = out["reproduction_of_official_O5"]
    print("wrote", os.path.relpath(OUT_JSON, ROOT), "and", os.path.relpath(OUT_MD, ROOT))
    print("reproduction:", json.dumps(rep))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
