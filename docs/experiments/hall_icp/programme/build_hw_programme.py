#!/usr/bin/env python3
"""Build (or --check) the A9.21 hardware-programme order record.

Writes hw_programme_a9_21_v1.json (from hw_programme_a9_21.document()) and HW_PROGRAMME_A9_21.md (rendered from the
JSON). The stage artifacts (H-1 freeze candidate, P1, P2, P3 v2, P4) embed hw_programme_a9_21.artifact_view(...), which
refuses a stale record, so rebuild this first. stdlib only; deterministic.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import hw_programme_a9_21 as PROG  # noqa: E402

ROOT = PROG.ROOT


def render_md(doc: dict) -> str:
    d = doc["decision"]
    out = ["# A9.21 hardware-programme order (items 6-11)", "",
           f"Generated by `{doc['generated_by']}` from `{PROG.RECORD_REL}`; library `{doc['library']}`; test "
           f"`{doc['test']}`. Do not edit by hand.", "",
           f"Decision: {d['cite']}. {d['governs']}.", "",
           "Entry statuses (fail closed): " + ", ".join(f"`{s}`" for s in doc["entry_status_vocabulary"]) +
           ". None of them is a test result, PASS, GO or a start authorisation.", "",
           "## Owner items (verbatim)", ""]
    for n, it in doc["owner_items_verbatim"].items():
        out += [f"> {it['verbatim']}", "", f"Steps: {', '.join(it['steps'])}", ""]
    out += ["## Order", "", "| # | step | item | artifact | kind | predecessors | entry preconditions | status now |",
            "|---|---|---|---|---|---|---|---|"]
    for s in doc["steps"]:
        preds = ", ".join(f"{p['step']} ({p['basis']})" for p in s["predecessors"]) or "-"
        pres = "; ".join(f"{p['id']}: {p['what']} (before {p['freeze_before']}; {p['enforced_by']}; "
                         f"{', '.join(x['question_id'] for x in p['sources'])})" for p in s["entry_preconditions"]) \
            or "-"
        out.append(f"| {s['order_index']} | {s['id']} | {s['owner_item']} | `{s['artifact_path']}` | {s['kind']} | "
                   f"{preds} | {pres} | {s['entry_status_now']} |")
    r = doc["icp_campaign_rule"]
    out += ["", "## Registered ICP gas / mode campaigns (item 8)", "",
            f"Steps {', '.join(r['steps'])}; supply modes {json.dumps(r['supply_mode'])}; required "
            f"{', '.join(r['required'])}; closures registered before the first record: {', '.join(r['closures'])}.",
            "", "Refused: " + "; ".join(r["refusals"]) + ".", "", r["content_checks"] + ".", "",
            "## H-1 S7.2 selection (item 6)", "",
            f"Criteria {', '.join(doc['h1_selection_rule']['criteria'])}; status "
            f"`{doc['h1_selection_rule']['status']}` / `{doc['h1_selection_rule']['optimisation_basis']}`; refused "
            "inputs: " + ", ".join(doc["h1_selection_rule"]["refused_inputs"]) + ".", "",
            "## AG-12 / AG-13 dependency (item 11; gates live in F9)", ""]
    for g, v in doc["ag12_ag13_now"].items():
        out.append(f"- {g}: programme input `{v['programme_input']}` (gate in `{v['gate_location']}`)")
    out += ["", "## Recorder readings (owner may reverse)", ""]
    for rr in doc["recorder_readings"]:
        out.append(f"- {rr['id']} (item {rr['item']}, {rr['status']}): {rr['reading']}" +
                   (f". Alternative: {rr['alternative']}" if rr.get("alternative") else ""))
    out += ["", "## What this is not", ""] + [f"- {w}" for w in doc["what_this_is_not"]] + [""]
    return "\n".join(out)


def outputs() -> dict:
    doc = PROG.document()
    return {ROOT / PROG.RECORD_REL: PROG.canonical(doc), ROOT / PROG.MD_REL: render_md(doc)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify the committed outputs reproduce")
    a = ap.parse_args(argv)
    outs = outputs()
    if a.check:
        bad = [str(p.relative_to(ROOT)) for p, txt in outs.items()
               if not p.exists() or p.read_text(encoding="utf-8") != txt]
        if bad:
            print("STALE: " + ", ".join(bad))
            return 1
        print("OK: hw_programme_a9_21_v1.json and HW_PROGRAMME_A9_21.md are current")
        return 0
    for p, txt in outs.items():
        p.write_text(txt, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
