"""P1 ICP bench campaign driver - pure, deterministic (lane fo_a9_6_p1_workflow_completion, owner A9.6 sec. 8 / 14).

run_campaign(bundle) takes ONE campaign bundle - manifest, P1-G0 registrations and every raw record of any P1 stage -
and returns the complete campaign report (schema p1_campaign_report_schema_v1.json in this directory, generated by
build_p1_icp_bench.py):

  P1-W01 P1-G0 readiness / safety           reduce_readiness            (p1_g0_readiness)
  P1-W02 RF cold checkout                   reduce_rf_cold_checkout     (rf_cold_checkout: dummy load, unlit antenna)
  P1-W03 ICP ignition (Ar, G-REUSE)         reduce_ignition             (ignition_attempt)
  P1-W04 electron-current surface           reduce_operating_points     (icp_operating_point)
  P1-W05 ICP-45 discharge-OFF capacity      icp45a_candidates / icp45a_evaluate
  P1-W06 RF-OFF paired correction           facility_pair_mismatches / facility_electron_check / i_e_cap_signed
  P1-W07 Kirchhoff closure (A9.5 owner)     kirchhoff_closure
  P1-W08 stable region -> P2 handoff        stable_region_handoff       (stability_dwell)
  P1-W09 Takahashi-like topology control    reduce_topology_control     (topology_control_sequence; never a gate)
  P1-W10 Hall-ON NEUTRALIZATION_CONSISTENCY neutralization_consistency + the 'after capacity' entry rule

Fail-closed rules (A9.6 sec. 14; one test each in tests/test_p1_icp_bench.py):
  * raw records are never dropped: every record appears in raw_records verbatim and exactly once in raw_record_index
    with its disposition (REDUCED / OUT_OF_DOMAIN / REFUSED_INVALID_RECORD) and verbatim reasons;
  * a record that fails validation is REFUSED_INVALID_RECORD with the reducer's error text kept verbatim (never
    silently repaired); missing required data therefore never reaches a result, and no field of the report is PASS;
  * synthetic and measured evidence in one bundle -> refused (MixedEvidenceError, no report);
  * a record outside a registered stage / operating domain, or taken before its stage entry (P1-G0) is met, is
    OUT_OF_DOMAIN - reported separately and never counted as a failure;
  * missing registrations (I_d,max,H1, margin rule, closure rule, match rule, stable criteria) give NOT_EVALUATED /
    NOT_EVALUATED_REGISTRATION, never a default.
Pure: stdlib (copy, hashlib, json) + the sibling p1_reducer; no file or network I/O (the CLI p1_campaign_cli.py does
the I/O).
"""
