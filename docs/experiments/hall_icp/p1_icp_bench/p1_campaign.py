def _canon(obj):
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def _check_bundle(bundle):
    if not isinstance(bundle, dict):
        raise CampaignInputError("campaign bundle must be an object")
    for k in ("schema", "manifest", "registrations", "records"):
        if k not in bundle:
            raise CampaignInputError("campaign bundle: missing '%s'" % k)
    if bundle["schema"] != BUNDLE_SCHEMA:
        raise CampaignInputError("campaign bundle schema %r is not %s" % (bundle["schema"], BUNDLE_SCHEMA))
    man = bundle["manifest"]
    if not isinstance(man, dict) or any(not isinstance(man.get(k), str) or not man.get(k).strip()
                                        for k in MANIFEST_REQUIRED):
        raise CampaignInputError("manifest needs non-empty %s" % list(MANIFEST_REQUIRED))
    if man["evidence_kind"] not in EVIDENCE_KINDS:
        raise CampaignInputError("manifest.evidence_kind %r not in %s" % (man["evidence_kind"], EVIDENCE_KINDS))
    reg = bundle["registrations"]
    if not isinstance(reg, dict):
        raise CampaignInputError("registrations must be an object")
    for k in REGISTRATION_KEYS:
        if k not in reg:
            raise CampaignInputError("registrations: key '%s' missing (null is the explicit 'not registered' state; "
                                     "no hidden default)" % k)
        if reg[k] is None and k not in REGISTRATION_NULLABLE:
            raise CampaignInputError("registrations.%s may not be null" % k)
    extra = sorted(set(reg) - set(REGISTRATION_KEYS))
    if extra:
        raise CampaignInputError("registrations: unknown keys %s" % extra)
    if not isinstance(reg["registration_set_id"], str) or not reg["registration_set_id"].strip():
        raise CampaignInputError("registrations.registration_set_id must be a non-empty string")
    doms = reg["operating_domains"]
    if not isinstance(doms, dict):
        raise CampaignInputError("registrations.operating_domains must be an object {stage_id: domain}")
    for st, d in doms.items():
        if not isinstance(d, dict) or not isinstance(d.get("domain_id"), str) or not d["domain_id"].strip():
            raise CampaignInputError("operating domain of %r needs a domain_id" % st)
        for f, v in d.items():
            if f == "domain_id":
                continue
            if f not in DOMAIN_FACTORS:
                raise CampaignInputError("operating domain of %r: unknown factor %r (allowed %s)"
                                         % (st, f, sorted(DOMAIN_FACTORS)))
            if (not isinstance(v, list) or len(v) != 2 or any(isinstance(x, bool) or not isinstance(x, (int, float))
                                                               for x in v) or v[0] > v[1]):
                raise CampaignInputError("operating domain of %r: factor %r must be [min, max]" % (st, f))
    if not isinstance(reg["facility_pairs"], list):
        raise CampaignInputError("registrations.facility_pairs must be a list (empty when none)")
    recs = bundle["records"]
    if not isinstance(recs, list):
        raise CampaignInputError("records must be a list")
    return man, reg, recs


def _rid(rec, i):
    rid = rec.get("record_id") if isinstance(rec, dict) else None
    return rid if isinstance(rid, str) and rid.strip() else "RAW-INDEX-%04d" % i


def _validate(rec):
    """Dispatch by record_kind; raises P1RecordError subclasses with the reducer's own text."""
    if not isinstance(rec, dict):
        raise red.MissingInputError("raw record is not an object")
    kind = rec.get("record_kind")
    if kind == "p1_g0_readiness":
        return red.reduce_readiness(rec)
    if kind == "rf_cold_checkout":
        red.validate_cold_checkout(rec)
    elif kind == "ignition_attempt":
        red.validate_ignition(rec)
    elif kind == "icp_operating_point":
        red.validate_operating_point(rec)
    elif kind == "stability_dwell":
        red.validate_dwell(rec)
    elif kind == "topology_control_sequence":
        red.reduce_topology_control(rec)
    else:
        raise red.P1RecordError("record_kind %r not in %s" % (kind, list(red.RECORD_KINDS)))
    if rec["stage_id"] not in KIND_STAGES[kind]:
        raise red.P1RecordError("record %r: stage %r not a stage of record_kind %s (%s)"
                                % (rec.get("record_id"), rec["stage_id"], kind, list(KIND_STAGES[kind])))
    return None


def _domain_reasons(rec, doms):
    st = rec["stage_id"]
    if st == G0_STAGE:
        return []
    d = doms.get(st)
    if d is None:
        return ["stage %r has no registered operating domain (registrations.operating_domains)" % st]
    out = []
    for f, (a, b) in DOMAIN_FACTORS.items():
        sub = rec.get(a)
        if not isinstance(sub, dict) or b not in sub:
            continue
        if f == "P_fwd_W" and float(sub[b]) == 0.0:
            continue                      # RF-OFF record: the RF domain does not apply
        if f not in d:
            out.append("factor %s not registered in operating domain %r of stage %s" % (f, d["domain_id"], st))
            continue
        v = float(sub[b])
        if not (d[f][0] <= v <= d[f][1]):
            out.append("%s = %r outside registered operating domain %r of stage %s [%r, %r]"
                       % (f, v, d["domain_id"], st, d[f][0], d[f][1]))
    return out


def _walk_no_pass(obj, path="report"):
    if isinstance(obj, dict):
        for k, v in obj.items():
            _walk_no_pass(v, path + "." + str(k))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            _walk_no_pass(v, "%s[%d]" % (path, i))
    elif isinstance(obj, str) and obj.strip().upper() == "PASS":
        raise red.P1RecordError("campaign report self-check: %s = 'PASS' (never produced by P1)" % path)


def _capacity_shown_points(icp, margin_rule):
    """h1_point_ids at which discharge-OFF capacity is shown (P1-W10 entry): a CLOSURE_VALID_CANDIDATE whose own
    M_n,LB > 0 under both P1Q-19 treatments, with the ICP-45 evaluation not NOT_EVALUATED."""
    if icp.get("status") not in ("EVALUATED_ENGINEERING_ONLY", "SYNTHETIC_TEST_ONLY_NOT_EVIDENCE"):
        return {}
    k = float(margin_rule["k_one_sided"])
    shown = {}
    for c in icp.get("candidates", []):
        alts = red._p1q19_alternatives(c, icp["I_d_max_H1_A"], k, float(margin_rule["u_I_e_A"]),
                                       float(margin_rule["u_I_d_max_A"]))
        if alts["agree"] and alts[red.P1Q19_ALTERNATIVES[0]]["condition_met"] is True:
            shown.setdefault(c["h1_point_id"], []).append(c["record_id"])
    return shown


def run_campaign(bundle):
    """Complete P1 campaign report from one bundle (see module docstring). Raises CampaignInputError on a malformed
    bundle / registrations and MixedEvidenceError on mixed synthetic / measured records; every per-record problem is
    kept in the report instead."""
    man, reg, recs = _check_bundle(bundle)
    synthetic = man["evidence_kind"] == "SYNTHETIC_TEST_ONLY"
    raw = copy.deepcopy(recs)
    ids = [_rid(r, i) for i, r in enumerate(raw)]
    if len(set(ids)) != len(ids):
        raise CampaignInputError("duplicate record_id in the bundle: %s" % sorted({i for i in ids if ids.count(i) > 1}))
    mixed = [i for i, r in zip(ids, raw) if isinstance(r, dict) and isinstance(r.get("synthetic"), bool)
             and r["synthetic"] != synthetic]
    if mixed:
        raise MixedEvidenceError("campaign %r is %s but records %s say synthetic = %r: synthetic and measured evidence "
                                 "mixed - refused (A9.6 sec. 14; a synthetic record never suppresses or substitutes a "
                                 "measured one)" % (man["campaign_id"], man["evidence_kind"], mixed, not synthetic))
    index = {i: {"record_id": i, "record_kind": (r.get("record_kind") if isinstance(r, dict) else None),
                 "stage_id": (r.get("stage_id") if isinstance(r, dict) else None), "disposition": None,
                 "reasons": []} for i, r in zip(ids, raw)}
    valid, readiness = {}, []
    for i, r in zip(ids, raw):
        try:
            res = _validate(r)
        except red.P1RecordError as e:
            index[i].update({"disposition": "REFUSED_INVALID_RECORD", "reasons": [str(e)],
                             "error_class": type(e).__name__})
            continue
        valid[i] = r
        if res is not None:
            readiness.append(res)
    # P1-G0: the latest readiness record governs (by timestamp_utc, then record_id)
    g0 = None
    g0_recs = sorted((valid[x["record_id"]]["timestamp_utc"], x["record_id"], x) for x in readiness)
    if g0_recs:
        g0 = g0_recs[-1][2]
        g0_ts = g0_recs[-1][0]
    g0_met = g0 is not None and g0["g0_status"] == "G0_ENTRY_CONDITIONS_RECORDED"
    doms = reg["operating_domains"]
    for i, r in valid.items():
        why = _domain_reasons(r, doms)
        if r["stage_id"] != G0_STAGE:
            if not g0_met:
                why.append("stage entry not met: P1-G0 status %s (every stage after P1-S0 needs "
                           "G0_ENTRY_CONDITIONS_RECORDED)" % (g0["g0_status"] if g0 else "NO_READINESS_RECORD"))
            elif str(r["timestamp_utc"]) < str(g0_ts):
                why.append("stage entry not met: record taken before the governing P1-G0 readiness record %r"
                           % g0["record_id"])
        if why:
            index[i].update({"disposition": "OUT_OF_DOMAIN", "reasons": why})
        else:
            index[i]["disposition"] = "REDUCED"
    use = {i: r for i, r in valid.items() if index[i]["disposition"] == "REDUCED"}
    by_kind = {}
    for i in ids:
        if i in use:
            by_kind.setdefault(use[i]["record_kind"], []).append(use[i])
    # P1-W02 RF cold checkout
    cold = red.reduce_rf_cold_checkout(by_kind.get("rf_cold_checkout", []))
    lv = {"rf_chain_status": cold["rf_chain_status"], "verified_loss_ids": list(cold["verified_loss_ids"])}
    # P1-W03 ignition
    ign = red.reduce_ignition(by_kind.get("ignition_attempt", []))
    # P1-W04..W07, W10
    ops = by_kind.get("icp_operating_point", [])
    op_ids = {r["record_id"] for r in ops}
    pairs, pair_notes = [], {}
    for p in reg["facility_pairs"]:
        if not isinstance(p, list) or len(p) != 2 or p[0] not in index or p[1] not in index:
            raise CampaignInputError("registered facility pair %r refers to records not in the bundle" % (p,))
        bad = []
        for member, tag in ((p[0], "RF-ON"), (p[1], "RF-OFF")):
            d = index[member]["disposition"]
            if d != "REDUCED":
                bad.append((d, "paired %s record %r is %s: %s" % (tag, member, d, "; ".join(index[member]["reasons"]))))
        if reg["facility_match"] is None:
            bad.append(("REDUCED", "facility pressure-match rule not registered (P1-IT-37): the RF-OFF correction "
                                   "cannot be formed"))
        if bad:
            pair_notes[p[0]] = (p[1], bad)
        else:
            pairs.append(p)
    cap_rec = {r["record_id"] for r in ops if r["record_class"] == red.CAPACITY_LABEL
               and r["hall_discharge_state"] == "OFF" and float(r["rf"]["P_fwd_W"]) > 0.0}
    registered = reg["i_d_max_registration"] is not None and reg["margin_rule"] is not None
    ic_reg = reg["i_d_max_registration"] if registered else None
    ic_mr = reg["margin_rule"] if registered else None
    if ops:
        opr = red.reduce_operating_points(ops, ic_reg, ic_mr, pairs, reg["facility_match"], reg["closure_rule"], lv)
    else:
        opr = {"surface": [], "facility_electron_checks": [], "summary": {"icp45a": red.icp45a_evaluate([], None)}}
    icp = opr["summary"]["icp45a"]
    fac_by_on = {f["records"][0]: f for f in opr["facility_electron_checks"]}
    # capacity point outcomes
    outcomes = {}
    if registered:
        for c in icp.get("candidates", []):
            outcomes[c["record_id"]] = {"record_id": c["record_id"], "outcome": c["outcome"], "reasons": [],
                                        "rf_off_record_id": c["rf_off_record_id"], "I_e_cap_A": c["I_e_cap_A"],
                                        "closure": c["closure"], "eligibility": c["eligibility"]}
        for key in ("excluded_records", "not_evaluated_instrument_records", "not_evaluated_uncertainty_records"):
            for e in icp.get(key, []):
                if e["record_id"] in cap_rec:
                    outcomes[e["record_id"]] = dict(e)
    elif reg["i_d_max_registration"] is not None:        # margin rule missing: outcomes still formed per point
        c, ex, ins, unc = red.icp45a_candidates(ops, reg["i_d_max_registration"], fac_by_on, reg["closure_rule"])
        for e in c + ex + ins + unc:
            if e["record_id"] in cap_rec:
                outcomes[e["record_id"]] = dict(e)
        icp = dict(icp, reason="margin rule not registered (P1-IT-29): ICP45 = NOT_EVALUATED; " + icp["reason"])
    else:
        for rid in sorted(cap_rec):
            clo = red.kirchhoff_closure(use[rid], reg["closure_rule"]) if reg["closure_rule"] is not None else None
            outcomes[rid] = {"record_id": rid, "outcome": "NOT_EVALUATED_REGISTRATION", "closure": clo,
                             "reasons": ["I_d,max,H1 and its registered H-1 points not registered (A9.4 "
                                         "execution_decisions.i_d_max_h1; A9.5 P1Q-16 condition 4): NOT_EVALUATED"]}
    for rid in sorted(cap_rec):
        o = outcomes.setdefault(rid, {"record_id": rid, "outcome": "EXCLUDED", "reasons": []})
        o["reasons"] = list(o.get("reasons") or [])
        for d, note in pair_notes.get(rid, (None, []))[1]:
            o["reasons"].append(note)
            if d == "OUT_OF_DOMAIN":
                o["outcome"] = "OUT_OF_DOMAIN"
    for i, r in valid.items():                            # RF-ON capacity records outside the domain
        if (index[i]["disposition"] == "OUT_OF_DOMAIN" and r["record_kind"] == "icp_operating_point"
                and r["record_class"] == red.CAPACITY_LABEL and float(r["rf"]["P_fwd_W"]) > 0.0):
            outcomes[i] = {"record_id": i, "outcome": "OUT_OF_DOMAIN", "reasons": list(index[i]["reasons"])}
    for o in outcomes.values():
        if o["outcome"] not in red.POINT_OUTCOMES:
            raise red.P1RecordError("internal: point outcome %r not in vocabulary" % o["outcome"])
        index[o["record_id"]]["capacity_point_outcome"] = o["outcome"]
    # Kirchhoff closures (every capacity-class record, RF-ON and RF-OFF)
    closures = []
    if reg["closure_rule"] is not None:
        for r in ops:
            if r["record_class"] == red.CAPACITY_LABEL:
                closures.append(red.kirchhoff_closure(r, reg["closure_rule"]))
    # P1-W10 consistency rows with the 'after capacity' entry rule
    shown = _capacity_shown_points(icp, reg["margin_rule"]) if registered else {}
    cons = []
    for row in icp.get("neutralization_consistency", []):
        row = dict(row)
        if row["h1_point_id"] in shown:
            row["entry_capacity_records"] = shown[row["h1_point_id"]]
            row["row_status"] = "DESCRIPTIVE_CONSISTENCY_CHECK_NOT_A_GATE"
            row["reasons"] = []
        else:
            row["row_status"] = "OUT_OF_DOMAIN"
            row["reasons"] = ["P1-S7H entry not met: discharge-OFF capacity not shown at h1_point_id %r (A9.4 P1Q-10 "
                              "'after discharge-OFF capacity has been shown'); never counted as a failure"
                              % row["h1_point_id"]]
        cons.append(row)
    hall_on_ids = {r["record_id"] for r in ops if r["hall_discharge_state"] == "ON"}
    listed = {r["record_id"] for r in cons}
    for rid in sorted(hall_on_ids - listed):
        r = use[rid]
        index[rid]["reasons"].append("Hall-ON record not a P1-S7H RF-ON NEUTRALIZATION_CONSISTENCY row (stage %r, "
                                     "class %r, P_fwd %r W): surface row only" % (r["stage_id"], r["record_class"],
                                                                                  r["rf"]["P_fwd_W"]))
    # P1-W08 stable region
    ign_pts = {p["point_id"]: p for p in ign["points"]}
    stable = red.stable_region_handoff(by_kind.get("stability_dwell", []), {r["record_id"]: r for r in ops}, ign_pts,
                                       reg["stable_criteria"])
    # P1-W09 topology control
    topo = []
    for s in by_kind.get("topology_control_sequence", []):
        t = red.reduce_topology_control(s)
        t.update({"gate": False, "scoring": False, "evidence_class": red.REQUIRED_LABEL})
        topo.append(t)
    # excluded records (verbatim reasons) - never dropped
    excluded = []
    for i in ids:
        x = index[i]
        if x["disposition"] != "REDUCED":
            excluded.append({"record_id": i, "source": x["disposition"], "outcome": x["disposition"],
                             "reasons": list(x["reasons"]), "error_class": x.get("error_class")})
    for rid in sorted(outcomes):
        o = outcomes[rid]
        if o["outcome"] not in ("CLOSURE_VALID_CANDIDATE",) and index[rid]["disposition"] == "REDUCED":
            excluded.append({"record_id": rid, "source": "CAPACITY_POINT", "outcome": o["outcome"],
                             "reasons": list(o.get("reasons") or []), "error_class": None})
    for row in cons:
        if row["row_status"] == "OUT_OF_DOMAIN":
            excluded.append({"record_id": row["record_id"], "source": "NEUTRALIZATION_CONSISTENCY_ROW",
                             "outcome": "OUT_OF_DOMAIN", "reasons": list(row["reasons"]), "error_class": None})
    workflow = []
    for w in WORKFLOW:
        n = sum(1 for i in ids if index[i]["stage_id"] in w["stage_ids"])
        workflow.append({"id": w["id"], "name": w["name"], "stage_ids": w["stage_ids"], "reducer": w["reducer"],
                         "n_raw_records": n,
                         "n_reduced": sum(1 for i in ids if index[i]["stage_id"] in w["stage_ids"]
                                          and index[i]["disposition"] == "REDUCED")})
    report = {
        "schema": REPORT_SCHEMA, "campaign_id": man["campaign_id"], "evidence_kind": man["evidence_kind"],
        "any_synthetic": synthetic, "evidence_class": red.REQUIRED_LABEL,
        "input_sha256": hashlib.sha256(_canon(bundle).encode("utf-8")).hexdigest(),
        "registration_set_id": reg["registration_set_id"], "workflow": workflow,
        "readiness": {"governing_record_id": g0["record_id"] if g0 else None,
                      "g0_status": g0["g0_status"] if g0 else "NO_READINESS_RECORD", "records": readiness},
        "rf_cold_checkout": cold, "ignition_map": ign, "surface": opr["surface"],
        "facility_corrections": opr["facility_electron_checks"] + [
            {"records": [on, off], "pair_matched": False, "formed": False,
             "mismatch_reasons": [n for _, n in notes]}
            for on, (off, notes) in sorted(pair_notes.items())],
        "kirchhoff_closures": closures,
        "capacity": {"point_outcomes": [outcomes[k] for k in sorted(outcomes)],
                     "point_outcome_vocabulary": list(red.POINT_OUTCOMES), "icp45a": icp},
        "icp45_status": {"status": icp["status"], "condition_met": icp.get("condition_met"),
                         "m16_state": "PENDING_ICP45 (A9.2; unchanged by any P1 software result)",
                         "reason": icp.get("reason")},
        "stable_region": stable, "topology_control": topo, "neutralization_consistency": cons,
        "excluded_records": excluded,
        "raw_record_index": [index[i] for i in ids], "raw_records": raw,
        "statements": ["engineering-only, non-scoring (ENGINEERING_ONLY_NON_SCORING); no performance prediction",
                       "no PASS is produced for ICP-45, thermal, RF ratings or anode; ICP_COUPLED_THERMAL = "
                       "UNRESOLVED; RF_COMPONENT_RATINGS = TBD_AFTER_IMPEDANCE_MAP",
                       "OUT_OF_DOMAIN is reported separately and never counted as a failure",
                       "P_mains,in of the GROUND/FACILITY_ONLY generator is never P_bus"],
    }
    _walk_no_pass({k: v for k, v in report.items() if k != "raw_records"})
    return report
