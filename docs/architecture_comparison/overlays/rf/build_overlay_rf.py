def render(o):
    return json.dumps(o, indent=1, ensure_ascii=False) + "\n"


def merged_md(block):
    with open(OUT_MD, encoding="utf-8") as f:
        text = f.read()
    i, j = text.find(MD_BEGIN), text.find(MD_END)
    if i < 0 or j < 0 or j < i:
        raise OverlaySelfCheckError(f"{OUT_MD}: GENERATED markers not found")
    return text[:i] + block + text[j + len(MD_END):]


