def vlabel(k):
    """Markdown-safe label of a variant key such as 'cost_offset|eta_b=0.7'."""
    parts = k.split("|")
    if len(parts) == 1:
        return parts[0]
    return parts[0] + " (" + ", ".join(p.replace("eta_b=", "η_b ").replace("eta_v=", "η_v ") for p in parts[1:]) + ")"


def md_cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def fmt_iv(lo, hi, lo_open=False):
    return f"{'(' if lo_open else '['}{fmt(lo)}, {fmt(hi)}{']' if hi is not None else ')'}"


