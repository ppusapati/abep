class Glue:
    def __init__(self, b, amu_kg, m_n2_u):
        self.b = b
        self.mix = b.IonMix((b.IonSpecies("N2+", m_n2_u, 1, 1.0),))
        self.amu = amu_kg

    def ref(self, V, eta_u0, eta_b, eta_v, eta_ppu, mdot=1.0e-6):
        return self.b.HallReference(mdot_kg_s=mdot, V_d_V=V, eta_u=eta_u0, eta_b=eta_b, eta_v=eta_v,
                                    gamma_div=GAMMA_REF, eta_ppu_discharge=eta_ppu, mix=self.mix)

    def resp(self, case, ref):
        c = CASES[case]
        evs = ref.eta_v if c["eta_v_delivered"] == "= eta_v" else c["eta_v_delivered"]
        return self.b.PreionResponse(alpha=c["alpha"], chi=c["chi"], eta_v_delivered=evs, mix_delivered=ref.mix)

    def overhead(self, P):
        b = self.b
        return b.BusOverhead(arch=ARCH, source_bus_W={"rf_source": P},
                             delta_common_bus_W={k: 0.0 for k in b.COMMON_NON_DISCHARGE},
                             interstage_loss_bus_W=0.0, extra_ppu_bus_W=0.0)

    def Y(self, case, V, eta_b, eta_v, eta_ppu):
        """Largest payable bus W per A of DELIVERED ions (no fixed overhead): the supremum = marginal limit."""
        r = self.ref(V, 0.6, eta_b, eta_v, eta_ppu)
        return self.b.marginal_breakeven_delivered_cost(r, self.resp(case, r))


def closed_form_c(case, eta_b, eta_v):
    """BREAKEVEN_DERIVATION.md section 6.1 marginal C_del*,0 / Pi_H at equal mix (self-check only)."""
    if case == "add_only":
        return 1.0
    if case == "cost_offset":
        return 2.0 - eta_b
    return 2.0 / math.sqrt(eta_v) - eta_b


def n_d(case, eta_b, eta_v):
    """Normalized two-population coefficients for alpha = 1 at equal mix: R(x) = (1 + n x)^2 / (1 + d x),
    x = delta_s / eta_u0 (BREAKEVEN_DERIVATION.md section 5: n1 = R_T, d1 = R_P for alpha = 1)."""
    c = CASES[case]
    evs = eta_v if c["eta_v_delivered"] == "= eta_v" else c["eta_v_delivered"]
    n = math.sqrt(evs / eta_v)
    d = eta_b * (1.0 + (1.0 - c["chi"]) * (1.0 / eta_b - 1.0))
    return n, d


MARGINAL_TOL = 1e-12        # |2n - d - c| below this counts as exactly marginal: pays only in the limit x -> 0


def payable_poly(n, d, c, wf):
    """Coefficients (a3, a2, a1, a0) of F(x) = (1 + n x)^2 (1 - wf - c x) - (1 + d x) with the constant 1 cancelled
    analytically (F = x q(x) - wf (1 + n x)^2, q(x) = (2n - c - d) + (n^2 - 2nc) x - n^2 c x^2), so F is evaluated
    without cancellation near x = 0. F >= 0 <=> R(x)(1 - wf - c x) >= 1 (breakeven_v1 master condition at equal mix)."""
    return (-n * n * c, n * n - 2.0 * n * c - wf * n * n, 2.0 * n - c - d - 2.0 * wf * n, -wf)


def payable_x_interval(n, d, c, wf):
    """[x_lo, x_hi] (uncapped; x = delta_s/eta_u0) where a source whose delivered-ion bus cost is c * Pi_H breaks even
    with fixed overhead wf * P_d,bus0; None if no x > 0 pays. F is a cubic with a negative leading coefficient and
    F(0) = -wf <= 0, so on x > 0 the payable set is empty or ONE interval (contiguous by construction): with wf = 0 it
    is (0, x+] with x+ the positive root of q; with wf > 0 it lies between the two roots that bracket the local maximum
    of F, found by bisection on [0, x_max] and [x_max, (1 - wf)/c] (F < 0 at both outer ends)."""
    a3, a2, a1, a0 = payable_poly(n, d, c, wf)
    F = lambda x: ((a3 * x + a2) * x + a1) * x + a0
    if wf == 0.0:
        q0 = 2.0 * n - c - d
        if q0 <= MARGINAL_TOL:
            return None
        A, B = n * n * c, n * n - 2.0 * n * c
        return [0.0, (B + math.sqrt(B * B + 4.0 * A * q0)) / (2.0 * A)]
    x_end = (1.0 - wf) / c
    disc = 4.0 * a2 * a2 - 12.0 * a3 * a1
    if x_end <= 0.0 or disc < 0.0:
        return None
    x_max = max((-2.0 * a2 + sg * math.sqrt(disc)) / (6.0 * a3) for sg in (-1.0, 1.0))   # local maximum of F
    if not (0.0 < x_max < x_end) or F(x_max) < 0.0:
        return None

    def root(a, bb):            # F(a) and F(bb) have opposite signs
        fa = F(a) >= 0.0
        for _ in range(200):
            m = 0.5 * (a + bb)
            if (F(m) >= 0.0) == fa:
                a = m
            else:
                bb = m
        return 0.5 * (a + bb)
    return [root(0.0, x_max), root(x_max, x_end)]


