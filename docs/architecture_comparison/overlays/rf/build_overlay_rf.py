def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


def candidate_roots(extra_roots):
    roots = [ROOT] + [os.path.abspath(r) for r in extra_roots]
    env = os.environ.get("ABEP_OVERLAY_INPUT_ROOTS", "")
    roots += [os.path.abspath(r) for r in env.split(os.pathsep) if r.strip()]
    parent = os.path.dirname(ROOT)
    if os.path.basename(parent) == "worktrees":            # ROOT is a git worktree: search its siblings
        roots += sorted(p for p in glob.glob(os.path.join(parent, "*")) if os.path.isdir(p))
        main = os.path.dirname(os.path.dirname(parent))      # <main>/.claude/worktrees/<wt> -> <main>
        roots.append(main)
    out, seen = [], set()
    for r in roots:
        if r not in seen:
            seen.add(r)
            out.append(r)
    return out


def resolve_inputs(extra_roots):
    found, report = {}, {}
    roots = candidate_roots(extra_roots)
    for key, pin in INPUTS.items():
        tried = []
        for r in roots:
            p = os.path.join(r, pin["path"])
            if os.path.isfile(p):
                h = sha256_file(p)
                tried.append(f"{p} (sha256 {h[:12]}...)")
                if h == pin["sha256"]:
                    found[key] = (r, p)
                    break
        if key not in found:
            report[key] = tried
    if report:
        lines = [f"  {k}: {INPUTS[k]['path']} pinned sha256 {INPUTS[k]['sha256'][:12]}... from {INPUTS[k]['lane']} "
                 f"(commit {INPUTS[k]['commit']}); candidates: {v or 'none found'}" for k, v in report.items()]
        raise OverlayInputError("pinned overlay inputs not found (pass --input-root DIR, or set "
                                "ABEP_OVERLAY_INPUT_ROOTS, or merge the input lanes):\n" + "\n".join(lines))
    return found


def load_constants():
    """This checkout's abep_sim.constants (pinned). The pinned breakeven module imports it relatively."""
    if ROOT not in sys.path:
        sys.path.insert(0, ROOT)
    K = importlib.import_module("abep_sim.constants")
    if sha256_file(K.__file__) != INPUTS["constants_module"]["sha256"]:
        raise OverlayInputError(f"abep_sim.constants resolved to {K.__file__}, which differs from its pin")
    return K


def load_breakeven(found):
    """Load the pinned abep_sim/breakeven.py by file path under a private module name inside this checkout's abep_sim
    package (its only relative import, .constants, must be byte-identical to the one next to it in its own checkout)."""
    root, path = found["breakeven_module"]
    K = load_constants()
    sibling = os.path.join(root, "abep_sim", "constants.py")
    if not os.path.isfile(sibling) or sha256_file(sibling) != INPUTS["constants_module"]["sha256"]:
        raise OverlayInputError(f"{sibling}: constants next to the pinned breakeven module differ from the pin")
    b = sys.modules.get(PINNED_MODULE_NAME)
    if b is None:
        spec = importlib.util.spec_from_file_location(PINNED_MODULE_NAME, path)
        b = importlib.util.module_from_spec(spec)
        sys.modules[PINNED_MODULE_NAME] = b          # dataclasses resolve their module through sys.modules
        try:
            spec.loader.exec_module(b)
        except Exception:
            del sys.modules[PINNED_MODULE_NAME]
            raise
    if sha256_file(b.__file__) != INPUTS["breakeven_module"]["sha256"]:
        raise OverlayInputError(f"pinned breakeven module resolved to {b.__file__}, which differs from its pin")
    if b.BOUNDARY_VERSION != BOUNDARY_VERSION or b.BREAKEVEN_VERSION != "breakeven_v1":
        raise OverlayInputError(f"breakeven versions {b.BREAKEVEN_VERSION}/{b.BOUNDARY_VERSION} not as pinned")
    return b, K


