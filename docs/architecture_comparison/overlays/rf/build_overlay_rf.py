# ---------------------------------------------------------------------------------------------------- classification
def classify(lo, hi, lo_open, Y_lo, Y_hi, et_lo, et_hi):
    """Placement of a C_src interval [lo, hi] (hi None = unbounded; lo_open: lo itself excluded) against the payable
    condition C_src <= eta_t * Y with Y in [Y_lo, Y_hi] and eta_t in [et_lo, et_hi]."""
    top = et_hi * Y_hi
    if lo > top or (lo_open and lo >= top):
        return "ABOVE"
    if hi is not None and hi <= et_lo * Y_lo:
        return "BELOW"
    return "STRADDLES"


def overall(per_case):
    if all(per_case[c] == "ABOVE" for c in CASE_ORDER):
        return "CLEARLY_ABOVE_BREAKEVEN", None
    for c in CASE_ORDER:
        if per_case[c] == "BELOW":
            return "CLEARLY_BELOW", c
    return "STRADDLES", None


