def absorbed_per_beam_A(P_W, mdot_mg_s, eta_u, ion_mass_kg, e_c):
    """Absorbed W per A of singly charged beam ions: P / (eta_u * mdot / m_ion * e)."""
    I = eta_u * mdot_mg_s * 1e-6 / ion_mass_kg * e_c
    return P_W / I


def energy_per_injected(P_W, mdot_mg_s, feed_mass_kg, e_c):
    return P_W / (mdot_mg_s * 1e-6 / feed_mass_kg) / e_c


