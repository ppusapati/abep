def g6(x):
    if x is None:
        return None
    if isinstance(x, float) and not math.isfinite(x):
        return None
    return float(f"{float(x):.6g}")


def fmt(x, nd=4):
    if x is None:
        return "unbounded"
    if 1e4 <= abs(x) < 1e9:
        return f"{x:.0f}"
    return f"{x:.{nd}g}"


