def _sha(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _load(root: str, rel: str):
    p = os.path.join(root, rel)
    if not os.path.isfile(p):
        raise FileNotFoundError(f"required base input missing: {rel}")
    with open(p, encoding="utf-8") as f:
        return json.load(f) if rel.endswith(".json") else f.read()


def verify_pins(root: str) -> dict:
    out = {}
    for rel, want in list(PINS.items()) + list(DELIVERABLE_PINS.items()):
        p = os.path.join(root, rel)
        if not os.path.isfile(p):
            raise FileNotFoundError(f"pinned file missing: {rel}")
        got = _sha(p)
        if got != want:
            raise ValueError(f"pinned file {rel} sha256 {got} != pinned {want}; decisions and verified deliverables are "
                             f"immutable - refusing to build")
        out[rel] = want
    g0 = _load(root, G0)
    if g0.get("a5_sha256") != PINS[A5] or g0.get("verdict") != "CLEAN":
        raise ValueError("G0 record does not verify the pinned A5 hash with verdict CLEAN")
    a6 = _load(root, A6)
    if a6.get("follows_sha256") != PINS[A5]:
        raise ValueError("A6 does not follow the pinned A5 hash")
    a7 = _load(root, A7)
    if a7.get("follows_sha256") != [PINS[A5], PINS[A6]]:
        raise ValueError("A7 does not follow the pinned A5 and A6 hashes")
    return out


def _json_pointer(doc, pointer: str):
    cur = doc
    for part in pointer.lstrip("/").split("/"):
        if part == "":
            continue
        part = part.replace("~1", "/").replace("~0", "~")
        cur = cur[int(part)] if isinstance(cur, list) else cur[part]
    return cur


def _strings_under(obj, keys) -> list:
    """Every string value stored under one of ``keys`` anywhere in a JSON object (deterministic traversal order)."""
    out = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in keys and isinstance(v, str):
                out.append(v)
            else:
                out.extend(_strings_under(v, keys))
    elif isinstance(obj, list):
        for v in obj:
            out.extend(_strings_under(v, keys))
    return out


