#!/usr/bin/env python3
"""M16 subsystem maturity matrix v2 (fo_subsystem_maturity_matrix + fo_a6_integration_refresh): deterministic builder.

The central execution dashboard for the A5 Proposal Reference Architecture, turned into the A7 SCHEDULER: one row per
A5 baseline subsystem (16, names read verbatim from A5 ``architecture``) plus the reserved RF pre-ionization module
interface (row 17, reserved, not baseline flight hardware). Nine maturity columns per row, in this order:

    requirement -> allocation -> interface_status -> preliminary_design -> evidence_status -> procurement_status
    -> analysis_test_needed -> blocker -> owner

plus the A7 scheduler columns (owner addendum A7 ``m16_as_scheduler``): ``execution_state`` (READY / RUNNING / BLOCKED /
VERIFIED, derived by the fixed rule in ``SCHEDULER_RULE``), exactly one ``blocking_item`` per BLOCKED row, the A7 rollup
category, the A7 architecture-changing-blocker flag and the H2 lanes that mature the row.

Usage::

    python docs/budgets/subsystem_maturity/build_subsystem_maturity.py --write   # write the v2 JSON + Markdown
    python docs/budgets/subsystem_maturity/build_subsystem_maturity.py --check   # committed v2 files == rebuild

v1 (``subsystem_maturity_v1.json`` / ``SUBSYSTEM_MATURITY.md``) is kept byte-identical as history (sha256-pinned below;
it was generated by this script at commit 6e42ebb). This v2 builder never writes the v1 files.

What the builder does and does not do
  * The row CONTENT (which requirement, which allocation, which ids) is curated in ``ROWS`` below; every entry cites the
    file it was read from. The builder never computes a physical or performance number.
  * It verifies the pinned decision files (A4, A5, A6, A7, G0), the four merged A6 deliverables (pre-ionizer module ICD,
    Xe ledger, Phase-1 pre-registration framework, M16 v1) by sha256 and refuses to build on a mismatch.
  * It resolves EVERY typed reference id (HW-*, INS-*, S1A-*, S1-*, D-xx, MCQ-*, IF-*, G-xx, BOM items, RI-*, PMI-*,
    PMQ-*, Xe-ledger parameters, P1DQ-*, R-xx, H2 lanes, ...) against the file that defines it and raises on an unknown
    id, so no id is invented.
  * It reads the live state of referenced items (S1a/S1 condition states, LOCK-1 decision statuses, MCQ states,
    hardware-requirement statuses, BOM CBE bases, upstream-ICD field statuses, pre-ionizer ICD quantity statuses and
    closes_at, Xe-ledger parameter statuses and refusal state, Phase-1 threshold literals) and derives the interface
    status (FROZEN / PARTIAL / OPEN) and the execution state by fixed rules.
  * It READS docs/orchestration/lane_registry_v1.json to confirm that the H2 lanes are registered; that file is a mutable
    governance file and is never pinned (no hash of it is recorded).

Pure standard library. Deterministic: no clock, no randomness, sorted file listings, fixed JSON formatting. Nothing
here is wired into archengine; no frozen data, golden, prereg or campaign file is read for writing or modified.
"""
