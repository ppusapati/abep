def _script_text(root: str, rel: str) -> str:
    p = os.path.join(root, rel)
    if not os.path.isfile(p):
        raise FileNotFoundError(f"H2 lane workflow script missing: {rel}")
    with open(p, encoding="utf-8") as f:
        return f.read()


def _check_h2(root: str, reg: Registry, a7: dict, keys: list) -> dict:
    h2_wave = next(w for w in a7["waves"] if w["wave"] == "H2 hardware")
    out = {}
    for lane, spec in H2_LANES.items():
        if lane not in reg.registered:
            raise ValueError(f"H2 lane {lane} is not registered in {LANE_REGISTRY}")
        if spec["a7_title"] not in h2_wave["lanes"]:
            raise ValueError(f"A7 title {spec['a7_title']!r} not in A7 wave H2")
        txt = _script_text(root, spec["script"])
        if lane not in txt:
            raise ValueError(f"{spec['script']} does not name {lane}")
        for row, quote in spec["matures"].items():
            if row not in keys:
                raise KeyError(f"H2 mapping names unknown row {row}")
            if quote not in txt:
                raise ValueError(f"scope quote for {lane}/{row} not found verbatim in {spec['script']}: {quote!r}")
        contrib = spec["contributes"]
        if contrib == "ALL_OTHER_ROWS":
            contrib = [k for k in keys if k not in spec["matures"]]
        for row in contrib:
            if row not in keys:
                raise KeyError(f"H2 mapping names unknown row {row}")
        out[lane] = {"a7_title": spec["a7_title"], "registry_title": reg.registered_titles.get(lane),
                     "registered": True, "scope_source": f"{spec['script']} (ARGS_EMBEDDED prompt; read, not pinned)",
                     "matures": {r: {"scope_quote": q} for r, q in spec["matures"].items()},
                     "contributes": contrib}
    return out


